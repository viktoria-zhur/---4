"""Автоматические негативные сценарии: три типовых контрольных дефекта."""
from программы.классические_шифры import зашифровать_цезарем
from программы.современные_примитивы import aes_gcm_зашифровать, aes_gcm_расшифровать
from программы.электронная_подпись import создать_пару_ключей, подписать_документ, проверить_подпись


def выполнить_контрольные_дефекты():
    результаты = []
    bad = зашифровать_цезарем("TEST", "нечисловой")
    результаты.append({"дефект": "Некорректный ключ классического шифра", "ожидалось": "ошибка валидации", "фактически": bad["статус"], "пройден": bad["статус"] == "ошибка"})

    packet = aes_gcm_зашифровать("контроль целостности")
    tampered = packet["шифротекст"][:-1] + bytes([packet["шифротекст"][-1] ^ 1])
    dec = aes_gcm_расшифровать(tampered, packet["ключ"], packet["nonce"])
    результаты.append({"дефект": "Изменение шифротекста AES-GCM", "ожидалось": "ошибка_аутентификации", "фактически": dec["статус"], "пройден": dec["статус"] == "ошибка_аутентификации"})

    private, public = создать_пару_ключей()
    signature = подписать_документ("исходный документ", private)
    check = проверить_подпись("изменённый документ", signature, public)
    результаты.append({"дефект": "Изменение подписанного документа", "ожидалось": "недействительна", "фактически": check["статус"], "пройден": check["статус"] == "недействительна"})
    return {"всего": len(результаты), "пройдено": sum(x["пройден"] for x in результаты), "сценарии": результаты}
